def load_clip_model(device=DEVICE):
    model, preprocess = clip.load("ViT-B/32", device=device)
    model.eval()
    return model, preprocess

def get_clip_text_embedding(texts, model, device=DEVICE):
    with torch.no_grad():
        tokens = clip.tokenize(texts, truncate=True).to(device)
        emb = model.encode_text(tokens)
        emb = emb / emb.norm(dim=-1, keepdim=True)
        return emb.cpu().detach().tolist()

def get_clip_image_embedding(urls, model, preprocess, device=DEVICE):
    embs = []
    for url in urls:
        try:
            resp = requests.get(url, timeout=5)
            img = PILImage.open(io.BytesIO(resp.content)).convert("RGB")
            inp = preprocess(img).unsqueeze(0).to(device)
            with torch.no_grad():
                emb = model.encode_image(inp)
                emb = emb / emb.norm(dim=-1, keepdim=True)
                embs.append(emb.cpu().detach().tolist()[0])
        except:
            embs.append([0.0] * model.visual.output_dim)
    return embs

def init_pinecone(api_key, name, dim):
    pc = Pinecone(api_key=api_key)
    if name not in [i.name for i in pc.list_indexes()]:
        pc.create_index(
            name=name,
            dimension=dim,
            metric="cosine",
            spec=ServerlessSpec(cloud="aws", region="us-east-1")
        )
    return pc.Index(name)

def upload_vectors_to_pinecone(idx, embeddings, df):
    vecs = []
    for i, emb in enumerate(embeddings):
        md = {col: df.iloc[i][col] for col in ["product_name", "about_product", "img_link"]}
        vecs.append({"id": str(i), "values": emb, "metadata": md})
    for i in tqdm(range(0, len(vecs), 100), desc="Upload batches"):
        idx.upsert(vectors=vecs[i:i+100])

def rechercher_produits(query, idx, bm25, model, top_k=5, alpha=0.5):
    print(f"🔎 Requête : {query}")
    emb_q = get_clip_text_embedding([query], model)[0]
    res = idx.query(vector=emb_q, top_k=top_k*2, include_metadata=True)
    tokens = clean_text(query).split()
    scores = bm25.get_scores(tokens)
    max_s = max(scores) if max(scores) > 0 else 1
    reranked = []
    for m in res["matches"]:
        di = int(m.get("id", -1))
        if di < 0 or di >= len(scores): continue
        m["final_score"] = alpha * m.get("score",0) + (1-alpha) * (scores[di]/max_s)
        reranked.append(m)
    top = sorted(reranked, key=lambda x: x["final_score"], reverse=True)[:top_k]
    for m in top:
        md = m['metadata']
        print(f" {md.get('product_name')} — score {m['final_score']:.3f}")
        try:
            display(Image(url=md['img_link']))
        except:
            pass
    return top

def train_and_evaluate(
    df,
    feature_col,
    label_col,
    method='tfidf',
    test_size=0.2,
    random_state=42,
    cv_folds=5,
    grid_search=False
):
    X = df[feature_col].tolist()
    y = df[label_col].values
    counts = pd.Series(y).value_counts()
    stratify = y if counts.min() >= 2 else None
    X_tr, X_te, y_tr, y_te = train_test_split(
        X, y, test_size=test_size,
        random_state=random_state,
        stratify=stratify
    )
    if method == 'tfidf':
        vect = TfidfVectorizer(min_df=2, ngram_range=(1,2), stop_words='english')
        X_tr_feat, X_te_feat = vect.fit_transform(X_tr), vect.transform(X_te)
        clf = LogisticRegression(max_iter=1000)
    elif method == 'image':
        model_clip, preprocess = load_clip_model(DEVICE)
        X_tr_feat = get_clip_image_embedding(X_tr, model_clip, preprocess, DEVICE)
        X_te_feat = get_clip_image_embedding(X_te, model_clip, preprocess, DEVICE)
        vect = None; clf = LogisticRegression(max_iter=1000)
    else:
        model_clip, _ = load_clip_model(DEVICE)
        X_tr_feat = get_clip_text_embedding(X_tr, model_clip, DEVICE)
        X_te_feat = get_clip_text_embedding(X_te, model_clip, DEVICE)
        vect = None; clf = LogisticRegression(max_iter=1000)
    if grid_search:
        clf = GridSearchCV(clf, {'C':[0.01,0.1,1,10]}, cv=cv_folds, scoring='accuracy')
    clf.fit(X_tr_feat, y_tr)
    y_pred = clf.predict(X_te_feat)
    acc = accuracy_score(y_te, y_pred); pct = acc*100
    print(f" Accuracy: {acc:.4f} ({pct:.2f}%)")
    print(classification_report(y_te, y_pred))
    cm = confusion_matrix(y_te, y_pred)
    print(cm)
    if not grid_search:
        scores = cross_val_score(clf, X_tr_feat, y_tr, cv=cv_folds, scoring='accuracy')
        print(f" CV ({cv_folds}): mean={scores.mean():.4f}, std={scores.std():.4f}")
    return {'model':clf, 'vectorizer':vect, 'X_test':X_te, 'y_test':y_te, 'y_pred':y_pred}

