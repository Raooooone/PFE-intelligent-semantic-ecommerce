import os
import random
import numpy as np
import pandas as pd
from PIL import Image
from io import BytesIO
import requests
import matplotlib.pyplot as plt
from sklearn.model_selection import train_test_split
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.metrics import accuracy_score, confusion_matrix, classification_report
from sklearn.linear_model import LogisticRegression

IMAGE_DIR     = 'images'
CSV_FILE      = 'amazon.csv'
MIN_SAMPLES   = 5
TEST_SIZE     = 0.2
RANDOM_SEED   = 42
HIST_BINS     = 16
TEXT_MAX_FEAT = 300
TOP_N         = 5
EPS           = 1e-8

def load_visual_data(image_dir=IMAGE_DIR, csv_file=CSV_FILE):
    df = pd.read_csv(csv_file)
    df = df.dropna(subset=['img_link', 'product_id', 'category', 'about_product'])
    df = df.drop_duplicates('product_id').reset_index(drop=True)
    counts = df['category'].value_counts()
    df = df[df['category'].isin(counts[counts >= MIN_SAMPLES].index)].reset_index(drop=True)

    os.makedirs(image_dir, exist_ok=True)
    valid_rows = []
    for _, row in df.iterrows():
        pid, url = row['product_id'], row['img_link']
        try:
            img = Image.open(BytesIO(requests.get(url, timeout=5).content)).convert('RGB')
            if min(img.size) >= 64:
                img.save(os.path.join(image_dir, f"{pid}.jpg"))
                valid_rows.append(row)
        except Exception:
            continue
    df_valid = pd.DataFrame(valid_rows).reset_index(drop=True)
    counts = df_valid['category'].value_counts()
    df_valid = df_valid[df_valid['category'].isin(counts[counts >= MIN_SAMPLES].index)].reset_index(drop=True)

    descriptions = df_valid['about_product'].fillna("").tolist()
    tfidf = TfidfVectorizer(max_features=TEXT_MAX_FEAT, stop_words='english')
    text_feats = tfidf.fit_transform(descriptions).toarray()

    docs = []
    for i, row in df_valid.iterrows():
        pid = row['product_id']
        img_feat = extract_image_feat(os.path.join(image_dir, f"{pid}.jpg"))
        txt_feat = text_feats[i]
        docs.append((pid, np.concatenate([img_feat, txt_feat]), row['category']))

    pids, feats, labels = zip(*docs)
    X = np.stack(feats)
    y = np.array(labels)

    X_train, X_test, y_train, y_test, pid_train, pid_test = train_test_split(
        X, y, pids, test_size=TEST_SIZE,
        stratify=y, random_state=RANDOM_SEED
    )
    return X_train, X_test, y_train, y_test, tfidf, dict(zip(pids, labels)), pid_train, pid_test

def extract_image_feat(path, bins=HIST_BINS):
    img = Image.open(path).resize((128,128)).convert('RGB')
    arr = np.array(img)
    feats = []
    for c in range(3):
        h, _ = np.histogram(arr[:,:,c], bins=bins, range=(0,256), density=True)
        feats.append(h)
    gray = np.dot(arr[...,:3], [0.2989, 0.5870, 0.1140])
    h, _ = np.histogram(gray, bins=bins, range=(0,256), density=True)
    feats.append(h)
    return np.concatenate(feats)

def cosine_sim(a, b):
    return np.dot(a, b) / (np.linalg.norm(a) * np.linalg.norm(b) + EPS)

def knn_predict(k, X_train, y_train, pid_train, product_id, top_n=TOP_N):
    if product_id not in pid_train:
        raise ValueError("Product ID not found in training set")
    idx = pid_train.index(product_id)
    feat = X_train[idx]
    sims = [(other, cosine_sim(feat, f)) for other, f in zip(pid_train, X_train) if other != product_id]
    top = sorted(sims, key=lambda x: x[1], reverse=True)[:top_n]
    recs = [pid for pid, _ in top]
    cats = [y_train[pid_train.index(pid)] for pid in recs]
    return pd.DataFrame({'product_id': recs, 'category': cats})

def knn_predict_new_product(image_path, description, tfidf_vectorizer, X_train, y_train, pid_train, top_n=TOP_N):
    image_feat = extract_image_feat(image_path)
    text_feat = tfidf_vectorizer.transform([description]).toarray()[0]
    new_feat = np.concatenate([image_feat, text_feat])
    sims = [(pid, cosine_sim(new_feat, feat)) for pid, feat in zip(pid_train, X_train)]
    top = sorted(sims, key=lambda x: x[1], reverse=True)[:top_n]
    recs = [pid for pid, _ in top]
    cats = [y_train[pid_train.index(pid)] for pid in recs]
    return pd.DataFrame({'product_id': recs, 'category': cats})

def predict_knn_labels(X_train, y_train, X_test, k=TOP_N):
    y_pred = []
    for xi in X_test:
        sims = [cosine_sim(xi, xj) for xj in X_train]
        topk = np.argsort(sims)[-k:][::-1]
        votes = {}
        for idx in topk:
            cat = y_train[idx]
            votes[cat] = votes.get(cat, 0) + sims[idx]
        y_pred.append(max(votes, key=votes.get))
    return np.array(y_pred)

def evaluate_new_product_accuracy(
    image_path,
    description,
    true_cat,
    tfidf_vectorizer,
    X_train,
    y_train,
    pid_train,
    top_n=TOP_N
):

    recos_df = knn_predict_new_product(
        image_path,
        description,
        tfidf_vectorizer,
        X_train,
        y_train,
        pid_train,
        top_n=top_n
    )
    pred_cat = recos_df.iloc[0]['category']
    return (pred_cat == true_cat), pred_cat

def display_recommendations(recos_df, image_dir=IMAGE_DIR, cols=5):
    n = len(recos_df)
    rows = (n + cols - 1) // cols
    fig, axes = plt.subplots(rows, cols, figsize=(4*cols, 4*rows))
    axes = axes.flatten()
    for ax in axes:
        ax.axis('off')
    for i, (_, row) in enumerate(recos_df.iterrows()):
        pid = row['product_id']
        img_path = os.path.join(image_dir, f"{pid}.jpg")
        if os.path.exists(img_path):
            img = Image.open(img_path)
            axes[i].imshow(img)
            axes[i].set_title(f"{pid}\n{row['category'].split('|')[-1]}", fontsize=9)
    plt.tight_layout()
    plt.show()

